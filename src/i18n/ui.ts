export type Translate = (key: UIKey | (string & {}), vars?: Record<string, string | number>) => string;

export function useTranslations(lang: Lang): Translate {
  return (key, vars) => {
    let s: string = (ui[lang] as Record<string, string | undefined>)[key] ?? (en as Record<string, string>)[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

